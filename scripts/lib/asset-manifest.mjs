/**
 * Content-hash manifest for every runtime asset.
 *
 * The pipelines write fixed filenames, so nothing in a URL tells a browser that a
 * model changed. Hashing the bytes and putting the hash in the query string makes
 * each build a distinct cache key, which is what allows `/models/*` and
 * `/textures/*` to be served `immutable` honestly.
 *
 * Not hypothetical: those paths were once served `immutable, max-age=1y` on the
 * strength of a comment claiming they were content-addressed. They were not. An
 * early Draco-compressed car stayed pinned in browser caches against a loader
 * that no longer had a Draco decoder, and no rebuild or reload could dislodge it.
 *
 * Scanned rather than enumerated, so an asset added to `public/` cannot be
 * forgotten here — being absent from the manifest silently reverts that one file
 * to un-bustable caching.
 */

import { createHash } from "node:crypto";
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const PUBLIC_DIR = join(ROOT, "public");
const MANIFEST_PATH = join(ROOT, "src", "game", "config", "generated", "asset-manifest.json");

/** Directories under `public/` whose contents the runtime requests by URL. */
const SCANNED = ["models", "textures"];

/** Extensions worth hashing. Licences and notes are not fetched by the engine. */
const HASHED = /\.(glb|gltf|bin|jpg|jpeg|png|webp|ktx2|hdr|mp3|ogg|wav)$/i;

/** Short content hash. Long enough that a collision is not a real concern. */
export function hashBytes(bytes) {
  return createHash("sha256").update(bytes).digest("hex").slice(0, 10);
}

async function walk(directory) {
  const found = [];
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(path)));
    else if (HASHED.test(entry.name)) found.push(path);
  }
  return found;
}

/** Hash every runtime asset and return the URL → hash map. */
export async function collectAssetHashes() {
  const assets = {};
  for (const top of SCANNED) {
    for (const path of await walk(join(PUBLIC_DIR, top))) {
      const url = `/${posix.join(...relative(PUBLIC_DIR, path).split(/[\\/]/))}`;
      assets[url] = hashBytes(await readFile(path));
    }
  }
  // Sorted so the generated file does not churn on directory order.
  return Object.fromEntries(Object.entries(assets).sort(([a], [b]) => a.localeCompare(b)));
}

export async function writeAssetManifest() {
  const assets = await collectAssetHashes();
  await mkdir(dirname(MANIFEST_PATH), { recursive: true });
  await writeFile(
    MANIFEST_PATH,
    `${JSON.stringify(
      {
        note:
          "Generated by the asset pipelines. Content hashes are appended to asset " +
          "URLs so a rebuilt file is never served from a stale cache.",
        assets,
      },
      null,
      2,
    )}\n`,
  );
  return assets;
}

export { MANIFEST_PATH };
